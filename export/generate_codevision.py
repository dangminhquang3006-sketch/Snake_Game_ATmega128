#!/usr/bin/env python3
"""Generate the standalone two-file CodeVisionAVR firmware from all 7 sources."""

import argparse
from pathlib import Path
import re


ROOT = Path(__file__).resolve().parents[1]
SOURCES = (
    "drivers/display.c",
    "drivers/keypad.c",
    "drivers/timer.c",
    "drivers/led7seg.c",
    "drivers/lcd1602.c",
    "game/game.c",
    "main.c",
)
CONFIG = ROOT / "config/board_config.h"
LOCAL_INCLUDE = re.compile(r'^\s*#\s*include\s*"([^\"]+)"\s*$')


def render_firmware():
    included = set()

    def inline(path):
        path = path.resolve()
        relative = path.relative_to(ROOT).as_posix()
        if path in included:
            return ""
        included.add(path)
        if path == CONFIG:
            return '#include "board_config.h"\n'
        lines = [f"\n/* ===== BEGIN {relative} ===== */\n"]
        for line in path.read_text(encoding="utf-8").splitlines(keepends=True):
            match = LOCAL_INCLUDE.fullmatch(line.rstrip("\r\n"))
            if match:
                dependency = path.parent / match.group(1)
                if dependency.suffix != ".h":
                    raise ValueError(f"Expected a header include in {relative}: {line}")
                lines.append(inline(dependency))
            else:
                lines.append(line)
        lines.append(f"\n/* ===== END {relative} ===== */\n")
        return "".join(lines)

    banner = (
        "/* Generated by export/generate_codevision.py. Do not edit this file.\n"
        "   Same implementation as the 7-file firmware.\n"
        "   Compile ONLY snake_firmware.c; keep board_config.h beside it.\n"
        "   Requires CodeVisionAVR libraries and the existing board settings.\n"
        "   Edit original sources, then run the generator again. */\n"
    )
    source = banner + "".join(inline(ROOT / name) for name in SOURCES)
    return source.replace("\n", "\r\n").encode("utf-8")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--output-dir", type=Path, default=ROOT / "export/codevision",
        help="destination directory (default: export/codevision)",
    )
    parser.add_argument(
        "--check", action="store_true",
        help="verify that both generated files match current sources without writing",
    )
    args = parser.parse_args()
    artifacts = {
        "snake_firmware.c": render_firmware(),
        "board_config.h": CONFIG.read_bytes(),
    }
    if args.check:
        stale = [name for name, data in artifacts.items()
                 if not (args.output_dir / name).is_file()
                 or (args.output_dir / name).read_bytes() != data]
        if stale:
            parser.exit(1, "Missing or outdated export: " + ", ".join(stale) + "\n")
        print("PASS: exported files match original sources")
        return
    args.output_dir.mkdir(parents=True, exist_ok=True)
    for name, data in artifacts.items():
        destination = args.output_dir / name
        destination.write_bytes(data)
        print(destination)


if __name__ == "__main__":
    main()
